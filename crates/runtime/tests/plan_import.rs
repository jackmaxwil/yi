//! F0b, import: format 1 becomes format 2 explicitly and losslessly.
//!
//! Test plan. Import is `Op::Import`, never a side effect of a read. The importer
//! reads and validates the old file, stores the original bytes as an immutable
//! artifact under `artifacts/<sha256>` written with `create_new`, converts the
//! frontmatter, maps each `## <label>` body section to `todos[].note` up to 4 KiB
//! and a larger one to an artifact reference (never a cut), keeps unknown fields
//! under `extra` with provenance, maps `Check::Command` to one critical `cmd`
//! item marked `revalidate` and `Check::Stated` to a `LegacyUnverified`
//! requirement kept verbatim, imports todos already `Done` as history, writes the
//! genesis `import` record carrying the original digest and the mapping, and
//! writes `plan.json` last. The original `.md` stays on disk until a separate,
//! user confirmed cleanup.
//!
//! The contract mapping is F0c's: this stage keeps `Delegation.accept` verbatim,
//! which is the input that mapping reads, and pins that it survives the trip.
//!
//! What `plan/import.rs` does, since the comment ratchet keeps the file itself
//! terse. `run` resolves the `local://` source against the engine's cwd (any
//! other scheme, and any hashline fragment, is a refusal, because the importer
//! reads a file and never fetches a reference); reads it under one
//! `IMPORT_CAP_BYTES` cap, which both it and `read_legacy` take, so a huge body
//! is a named refusal rather than a shortened document; refuses a frontmatter
//! over the 32 KiB `PLAN_CAP_BYTES` cap before serde sees it; parses format 1
//! through `Plan::parse_legacy`, which accepts format 1 alone; refuses a plan
//! that already has a format-2 checkpoint; writes the original bytes to
//! `artifacts/<sha256>`; then maps the sections. A section at or under the
//! 4 KiB `NOTE_MAX_BYTES` becomes `todos[].note`; a longer one becomes its own
//! blob and the todo carries `note_ref` in `extra` as `artifact:sha256:<hex>`,
//! so nothing is cut and no offset is ever taken into a `str`. Unknown keys
//! ride `extra` as the reader left them; the provenance of the conversion is
//! the genesis record, never a key in `plan.json`, which is why the expected
//! checkpoint below carries no import marker of its own.
//!
//! Crash matrix. Import is one transaction over the same commit protocol as any
//! other op, so the rows are the journal's rows read through the importer.
//!
//! | crash point | expected recovery | pinned by |
//! |---|---|---|
//! | after the artifact blob is written, before the `import` record commits | nothing was imported: the blob is an orphan under `artifacts/`, addressed by digest, and the retry writes the identical bytes (`create_new` on an existing identical digest is not an error the import fails on) | `import_preserves_all_markdown_and_large_notes` |
//! | after the `import` record commits, before `plan.json` is written | imported: the checkpoint is regenerated by reducing the journal, and the format-1 file is still on disk and still untouched | `plan_recovery::recovery_reduces_events_without_dispatching_effects` |
//! | after the whole import, on a binary two releases newer | the format-1 reader is kept for two releases, so a skipped release still imports rather than refusing the file | `skipped_release_can_still_import_format_one` |
//! | never: a read of a format-1 file | read-only, with a notice naming `yi plan import <id>`; no record, no blob, no conversion | `plan_store::a_format_1_read_is_read_only_until_import` |
//!
//! Fixtures this file reads: `fixtures/plans/format1/campaign.md` (exactly what
//! the campaign walkthrough writes today, sha256
//! `00d2b1d18888b753ed61db90efefada70e92af05096d07c361489ca1d7cc1987`), the
//! expected `fixtures/plans/format2/campaign/` (`plan.json` and the genesis
//! `ops.jsonl`), and `fixtures/plans/format1/large-section.md`, whose one body
//! section is 6,144 bytes and must land as an artifact reference.

